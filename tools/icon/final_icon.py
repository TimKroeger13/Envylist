"""
The Envylist launcher icon: concept G6 "Liste mit Neider".
Two finished tasks, and the unfinished yellow one glares up at them.

    python tools/icon/final_icon.py --preview   # preview sheet only
    python tools/icon/final_icon.py             # write the app icons + docs/icon.png

Rendered with headless Chrome so the result matches the approved preview exactly.
Outputs:
  app/src/main/res/mipmap-*/ic_launcher_art.webp     full icon art (adaptive icon background layer)
  app/src/main/res/drawable/ic_launcher_monochrome.xml  themed (monochrome) icon
  docs/icon.png                                        512 px rounded tile for README / website
"""

import argparse
import os
import subprocess
import tempfile

from PIL import Image

from concepts import CHROME
from concepts_g import PURPLE, PURPLE_DARK, variant

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))

# Concept G6, moved up so the content sits optically centred in the tile.
ROWS = (25, 44)
ROW_H = 14
JY, JH = 63, 18
BX = (26, 82)
ICON = variant((PURPLE, PURPLE_DARK), rows=ROWS, row_h=ROW_H, jy=JY, jh=JH, look=(-0.6, -1), bx=BX)


def render(svg, size, path, view="0 0 108 108", radius=0):
    """Screenshot an SVG at an exact pixel size with headless Chrome."""
    svg = svg.replace('viewBox="0 0 108 108"', f'viewBox="{view}"', 1)
    html = (f'<!doctype html><html><head><style>html,body{{margin:0;background:transparent}}'
            f'div{{width:{size}px;height:{size}px;border-radius:{radius}px;overflow:hidden}}</style></head>'
            f'<body><div>{svg}</div></body></html>')
    with tempfile.NamedTemporaryFile("w", suffix=".html", delete=False, encoding="utf-8") as fh:
        fh.write(html)
        page = fh.name
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp.png"
    subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--default-background-color=00000000",
                    f"--screenshot={tmp}", f"--window-size={size},{size}", "file:///" + page.replace("\\", "/")],
                   check=True, capture_output=True)
    os.remove(page)
    img = Image.open(tmp).convert("RGBA").crop((0, 0, size, size))
    os.remove(tmp)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if path.endswith(".webp"):
        img.save(path, "WEBP", lossless=True)
    else:
        img.save(path)
    return img


def monochrome_vector():
    """Themed icon: the same shapes in one colour (Android tints it)."""
    x0, x1 = BX
    paths = []
    for y in ROWS:
        cy = y + ROW_H / 2
        paths.append(f'<path android:fillColor="#FF000000" android:pathData="M{x0 + 7},{y} H{x1 - 7} '
                     f'A7,7 0 0 1 {x1 - 7},{y + 14} H{x0 + 7} A7,7 0 0 1 {x0 + 7},{y} Z"/>')
    # unfinished task with two cut-out eyes (evenodd): a pill with two almond holes
    cy = JY + JH / 2
    pill = (f"M{x0 + 9},{JY} H{x1 - 9} A9,9 0 0 1 {x1 - 9},{JY + JH} H{x0 + 9} A9,9 0 0 1 {x0 + 9},{JY} Z")
    eyes = ""
    for ex in (54 - 13 * 0.62, 54 + 13 * 0.62):
        eyes += (f" M{ex - 6.5},{cy} Q{ex},{cy - 8.6} {ex + 6.5},{cy} Q{ex},{cy + 8.6} {ex - 6.5},{cy} Z")
    paths.append(f'<path android:fillColor="#FF000000" android:fillType="evenOdd" android:pathData="{pill}{eyes}"/>')
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            "<!-- Generated by tools/icon/final_icon.py - edit the script, not this file. -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n    '
            + "\n    ".join(paths) + "\n</vector>\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", action="store_true")
    args = ap.parse_args()
    svg = ICON("final")
    if args.preview:
        out = os.path.join(HERE, "concepts")
        big = render(svg, 300, os.path.join(out, "_big.png"), "18 18 72 72", 66)
        small = render(svg, 48, os.path.join(out, "_small.png"), "18 18 72 72", 11)
        rnd = render(svg, 48, os.path.join(out, "_round.png"), "18 18 72 72", 24)
        sheet = Image.new("RGBA", (420, 330), (236, 236, 236, 255))
        sheet.alpha_composite(big, (10, 10))
        sheet.alpha_composite(small, (330, 10))
        sheet.alpha_composite(rnd, (330, 70))
        sheet.save(os.path.join(out, "final_preview.png"))
        for n in ("_big.png", "_small.png", "_round.png"):
            os.remove(os.path.join(out, n))
        print("preview written")
        return
    res = os.path.join(ROOT, "app", "src", "main", "res")
    for folder, px in {"mdpi": 108, "hdpi": 162, "xhdpi": 216, "xxhdpi": 324, "xxxhdpi": 432}.items():
        render(svg, px, os.path.join(res, f"mipmap-{folder}", "ic_launcher_art.webp"))
    with open(os.path.join(res, "drawable", "ic_launcher_monochrome.xml"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(monochrome_vector())
    render(svg, 512, os.path.join(ROOT, "docs", "icon.png"), "18 18 72 72", 112)
    print("icons written")


if __name__ == "__main__":
    main()
